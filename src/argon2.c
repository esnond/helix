/* argon2id per rfc 9106 (v 0x13), matching the phc-winner-argon2
   reference implementation (the rfc 5.3 kat was generated by it; its
   h' emits 32 bytes per 64-byte hash, the first two blocks of each
   lane are h'-derived, and pass>0 fills xor the old block content).
   single threaded over up to 4 lanes, lane-major within a slice. */
#include <stdlib.h>
#include <string.h>

#include "argon2.h"
#include "blake2b.h"
#include "secure_mem.h"

#define SYNC_POINTS 4u
#define ARGON2ID    2u
#define QWORDS      128u /* 1024 bytes / 8 */
#define MAX_LANES   4u   /* profile uses 4; the supported lane cap */

typedef struct {
    uint64_t v[QWORDS];
} ablock;

static void store32_le(uint8_t* p, uint32_t v)
{
    p[0] = (uint8_t)v;
    p[1] = (uint8_t)(v >> 8);
    p[2] = (uint8_t)(v >> 16);
    p[3] = (uint8_t)(v >> 24);
}

static uint64_t load64_le(const uint8_t* p)
{
    int i;
    uint64_t v = 0;
    for (i = 7; i >= 0; i--)
        v = (v << 8) | (uint64_t)p[i];
    return v;
}

static void store64_le(uint8_t* p, uint64_t v)
{
    int i;
    for (i = 0; i < 8; i++)
        p[i] = (uint8_t)(v >> (8 * i));
}

static uint64_t rotr64(uint64_t v, unsigned n)
{
    return (v >> n) | (v << (64 - n));
}

/* rfc 9106 3.6, blamka */
static uint64_t blamka(uint64_t a, uint64_t b)
{
    return a + b + 2u * (uint64_t)(uint32_t)a * (uint32_t)b;
}

static void gb(uint64_t* a, uint64_t* b, uint64_t* c, uint64_t* d)
{
    *a = blamka(*a, *b);
    *d = rotr64(*d ^ *a, 32);
    *c = blamka(*c, *d);
    *b = rotr64(*b ^ *c, 24);
    *a = blamka(*a, *b);
    *d = rotr64(*d ^ *a, 16);
    *c = blamka(*c, *d);
    *b = rotr64(*b ^ *c, 63);
}

/* permutation p over the 4x4 register matrix held as 16 qwords */
static void round16(uint64_t* v)
{
    gb(&v[0], &v[4], &v[8], &v[12]);
    gb(&v[1], &v[5], &v[9], &v[13]);
    gb(&v[2], &v[6], &v[10], &v[14]);
    gb(&v[3], &v[7], &v[11], &v[15]);
    gb(&v[0], &v[5], &v[10], &v[15]);
    gb(&v[1], &v[6], &v[11], &v[12]);
    gb(&v[2], &v[7], &v[8], &v[13]);
    gb(&v[3], &v[4], &v[9], &v[14]);
}

/* out = p(r) ^ r ^ (old_out when with_xor), r = x ^ y. the two round
   passes: consecutive 16-qword groups first, then strided groups. */
static void fill_block(const ablock* x, const ablock* y, ablock* out,
                       int with_xor)
{
    ablock r, t;
    unsigned i, k;
    for (i = 0; i < QWORDS; i++) {
        r.v[i] = x->v[i] ^ y->v[i];
        t.v[i] = r.v[i];
    }
    if (with_xor)
        for (i = 0; i < QWORDS; i++)
            t.v[i] ^= out->v[i];
    for (k = 0; k < 8; k++)
        round16(&r.v[16 * k]);
    for (k = 0; k < 8; k++) {
        uint64_t v[16];
        unsigned q;
        for (q = 0; q < 8; q++) {
            v[2 * q] = r.v[2 * k + 16 * q];
            v[2 * q + 1] = r.v[2 * k + 1 + 16 * q];
        }
        round16(v);
        for (q = 0; q < 8; q++) {
            r.v[2 * k + 16 * q] = v[2 * q];
            r.v[2 * k + 1 + 16 * q] = v[2 * q + 1];
        }
    }
    for (i = 0; i < QWORDS; i++)
        out->v[i] = t.v[i] ^ r.v[i];
}

/* reference index_alpha: the window excludes the previous block and
   counts forward from the segment after the current slice (wrapping) */
static uint32_t start_position(uint32_t pass, uint32_t slice,
                               uint32_t seg_len)
{
    if (pass == 0)
        return 0;
    return (slice == SYNC_POINTS - 1u) ? 0u : (slice + 1u) * seg_len;
}

static uint32_t index_alpha(uint32_t pass, uint32_t slice, uint32_t idx,
                            uint32_t seg_len, uint32_t lane_len,
                            int same_lane, uint32_t j1)
{
    uint32_t ras, start;
    uint64_t sq;
    if (pass == 0) {
        if (slice == 0)
            ras = idx - 1u;
        else if (same_lane)
            ras = slice * seg_len + idx - 1u;
        else
            ras = slice * seg_len + ((idx == 0) ? (uint32_t)-1 : 0u);
    } else {
        if (same_lane)
            ras = lane_len - seg_len + idx - 1u;
        else
            ras = lane_len - seg_len + ((idx == 0) ? (uint32_t)-1 : 0u);
    }
    sq = ((uint64_t)j1 * j1) >> 32;
    start = start_position(pass, slice, seg_len);
    return (start + ras - 1u -
            (uint32_t)(((uint64_t)ras * sq) >> 32)) %
           lane_len;
}

/* address block = g(zero, g(zero, input)), counter starts at 1 */
static void next_addresses(const ablock* zero, ablock* addr, ablock* inb)
{
    inb->v[6]++;
    fill_block(zero, inb, addr, 0);
    fill_block(zero, addr, addr, 0);
}

static void make_addr_input(ablock* inb, uint32_t pass, uint32_t lane,
                            uint32_t slice, uint32_t m_blocks,
                            uint32_t passes)
{
    memset(inb, 0, sizeof *inb);
    inb->v[0] = pass;
    inb->v[1] = lane;
    inb->v[2] = slice;
    inb->v[3] = m_blocks;
    inb->v[4] = passes;
    inb->v[5] = ARGON2ID;
}

int helix_argon2id_full(const uint8_t* pwd, size_t pwd_len,
                        const uint8_t* salt, size_t salt_len,
                        const uint8_t* secret, size_t sec_len,
                        const uint8_t* ad, size_t ad_len,
                        uint32_t t, uint32_t m_kib, uint32_t lanes,
                        uint8_t* out, size_t out_len)
{
    uint32_t m_blocks, seg_len, lane_len, pass, slice, lane, idx, l;
    uint8_t h0[64], seed[72], blkbuf[1024];
    ablock zero, addr[MAX_LANES], inb[MAX_LANES];
    ablock* mem;
    blake2b_ctx bc;
    unsigned i;

    if (!pwd || !salt || !out || out_len == 0 || out_len > 64 ||
        lanes == 0 || lanes > MAX_LANES || t < 1)
        return -1;
    if ((secret && !sec_len) || (!secret && sec_len) || (ad && !ad_len) ||
        (!ad && ad_len))
        return -1;
    m_blocks = (m_kib / (4u * lanes)) * 4u * lanes;
    if (m_blocks < 8u * lanes)
        return -1;
    seg_len = m_blocks / (lanes * SYNC_POINTS);
    lane_len = seg_len * SYNC_POINTS;

    /* h0: le32(p)||le32(tau)||le32(m)||le32(t)||le32(v)||le32(y)||... */
    blake2b_init(&bc, 64);
    {
        uint8_t w[4];
        store32_le(w, lanes);
        blake2b_update(&bc, w, 4);
        store32_le(w, (uint32_t)out_len);
        blake2b_update(&bc, w, 4);
        store32_le(w, m_kib);
        blake2b_update(&bc, w, 4);
        store32_le(w, t);
        blake2b_update(&bc, w, 4);
        store32_le(w, 0x13u);
        blake2b_update(&bc, w, 4);
        store32_le(w, ARGON2ID);
        blake2b_update(&bc, w, 4);
        store32_le(w, (uint32_t)pwd_len);
        blake2b_update(&bc, w, 4);
        blake2b_update(&bc, pwd, pwd_len);
        store32_le(w, (uint32_t)salt_len);
        blake2b_update(&bc, w, 4);
        blake2b_update(&bc, salt, salt_len);
        store32_le(w, (uint32_t)sec_len);
        blake2b_update(&bc, w, 4);
        if (sec_len)
            blake2b_update(&bc, secret, sec_len);
        store32_le(w, (uint32_t)ad_len);
        blake2b_update(&bc, w, 4);
        if (ad_len)
            blake2b_update(&bc, ad, ad_len);
        blake2b_final(&bc, h0, 64);
    }

    mem = malloc((size_t)m_blocks * 1024u);
    if (!mem)
        return -2;
    memset(&zero, 0, sizeof zero);

    /* the first two blocks of each lane are h'(h0 || le32(k) || le32(l)) */
    memcpy(seed, h0, 64);
    for (l = 0; l < lanes; l++) {
        for (i = 0; i < 2; i++) {
            store32_le(seed + 64, i);
            store32_le(seed + 68, l);
            blake2b_long(blkbuf, 1024u, seed, 72u);
            for (idx = 0; idx < QWORDS; idx++)
                mem[(size_t)l * lane_len + i].v[idx] =
                    load64_le(blkbuf + 8 * idx);
        }
    }
    helix_memzero(seed, sizeof seed);
    helix_memzero(blkbuf, sizeof blkbuf);

    for (pass = 0; pass < t; pass++) {
        for (slice = 0; slice < SYNC_POINTS; slice++) {
            int independent = (pass == 0 && slice < 2u);
            uint32_t start_idx = (pass == 0 && slice == 0) ? 2u : 0u;
            if (independent)
                for (l = 0; l < lanes; l++)
                    make_addr_input(&inb[l], pass, l, slice, m_blocks, t);
            for (lane = 0; lane < lanes; lane++) {
                if (independent && start_idx == 2u)
                    next_addresses(&zero, &addr[lane], &inb[lane]);
                for (idx = start_idx; idx < seg_len; idx++) {
                    uint64_t j1, j2;
                    uint32_t ref_lane, ref_pos, j;
                    ablock* prev;
                    j = slice * seg_len + idx;
                    prev = (j == 0)
                               ? &mem[(size_t)lane * lane_len + lane_len - 1]
                               : &mem[(size_t)lane * lane_len + j - 1];
                    if (independent) {
                        if (idx % 128u == 0) {
                            inb[lane].v[6] = (uint64_t)(idx / 128u) + 1u;
                            fill_block(&zero, &inb[lane], &addr[lane], 0);
                            fill_block(&zero, &addr[lane], &addr[lane], 0);
                        }
                        j1 = addr[lane].v[idx % 128u] & 0xFFFFFFFFull;
                        j2 = addr[lane].v[idx % 128u] >> 32;
                    } else {
                        j1 = prev->v[0] & 0xFFFFFFFFull;
                        j2 = prev->v[0] >> 32;
                    }
                    ref_lane = (pass == 0 && slice == 0)
                                   ? lane
                                   : (uint32_t)(j2 % lanes);
                    ref_pos = index_alpha(pass, slice, idx, seg_len, lane_len,
                                          ref_lane == lane,
                                          (uint32_t)j1);
                    fill_block(prev,
                               &mem[(size_t)ref_lane * lane_len + ref_pos],
                               &mem[(size_t)lane * lane_len + j],
                               (pass > 0) ? 1 : 0);
                }
            }
        }
    }

    /* final: xor of the last block of each lane, then h' */
    {
        ablock acc;
        uint8_t xorbuf[1024];
        memset(&acc, 0, sizeof acc);
        for (l = 0; l < lanes; l++) {
            const ablock* tail =
                &mem[(size_t)l * lane_len + lane_len - 1];
            for (i = 0; i < QWORDS; i++)
                acc.v[i] ^= tail->v[i];
        }
        for (i = 0; i < QWORDS; i++)
            store64_le(xorbuf + 8 * i, acc.v[i]);
        blake2b_long(out, out_len, xorbuf, 1024u);
        helix_memzero(xorbuf, sizeof xorbuf);
    }
    helix_memzero(mem, (size_t)m_blocks * 1024u);
    free(mem);
    helix_memzero(h0, sizeof h0);
    return 0;
}

int helix_argon2id(const uint8_t* pwd, size_t pwd_len,
                   const uint8_t* salt, size_t salt_len,
                   uint32_t t, uint32_t m_kib, uint32_t lanes,
                   uint8_t* out, size_t out_len)
{
    return helix_argon2id_full(pwd, pwd_len, salt, salt_len, NULL, 0, NULL,
                               0, t, m_kib, lanes, out, out_len);
}
