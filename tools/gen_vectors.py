#!/usr/bin/env python3
"""generate src/wordlist.h, src/sha256_k.h, src/sha512_k.h and the
tests/*_vectors_inc.h headers.

all expected values come from python's hashlib/hmac stdlib or the official
bip-0039 vector set (trezor/python-mnemonic vectors.json, english section,
passphrase "TREZOR", cached in data/bip39_vectors.json).

    python3 tools/gen_vectors.py           regenerate in place
    python3 tools/gen_vectors.py --check   verify committed files match
"""
import hashlib
import hmac
import json
import os
import random
import sys
import urllib.request
from math import isqrt

WORDLIST_SHA256 = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"
VECTORS_URL = ("https://raw.githubusercontent.com/trezor/python-mnemonic/"
               "master/vectors.json")
VECTORS_CACHE = "data/bip39_vectors.json"
CHECK = "--check" in sys.argv


def emit(path, content):
    if CHECK:
        if open(path).read() != content:
            sys.stderr.write("MISMATCH: %s (run tools/gen_vectors.py)\n" % path)
            sys.exit(1)
    else:
        open(path, "w").write(content)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def icbrt(n):
    """integer cube root, newton"""
    if n == 0:
        return 0
    x = 1 << ((n.bit_length() + 2) // 3)
    while True:
        y = (2 * x + n // (x * x)) // 3
        if y >= x:
            return x
        x = y


def primes(count):
    out, c = [], 2
    while len(out) < count:
        if all(c % p for p in out):
            out.append(c)
        c += 1
    return out


def gen_wordlist():
    raw = open("data/bip39_english.txt", "rb").read()
    assert hashlib.sha256(raw).hexdigest() == WORDLIST_SHA256, "wordlist integrity"
    words = [l.strip() for l in raw.decode().splitlines() if l.strip()]
    assert len(words) == 2048
    body = ["#ifndef HELIX_WORDLIST_H", "#define HELIX_WORDLIST_H", "",
            "/* generated by tools/gen_vectors.py from data/bip39_english.txt",
            " * canonical bip-0039 english wordlist, 2048 words,",
            " * sha256 %s. do not edit. */" % WORDLIST_SHA256, "",
            "#define BIP39_WORDLIST_SIZE 2048", "",
            "static const char* const BIP39_WORDS[BIP39_WORDLIST_SIZE] = {"]
    body += ["    %s," % c_str(w) for w in words]
    body += ["};", "", "#endif", ""]
    emit("src/wordlist.h", "\n".join(body))
    print("src/wordlist.h: %d words" % len(words))


def gen_sha_tables():
    """fips 180-4 constants from first principles: frac parts of
    sqrt(prime) for the ivs and cbrt(prime) for the round constants."""
    p8 = primes(8)
    iv32 = [(isqrt(p << 64) & 0xFFFFFFFF) for p in p8]
    k32 = [(icbrt(p << 96) & 0xFFFFFFFF) for p in primes(64)]
    iv64 = [(isqrt(p << 128) & 0xFFFFFFFFFFFFFFFF) for p in p8]
    k64 = [(icbrt(p << 192) & 0xFFFFFFFFFFFFFFFF) for p in primes(80)]
    lines = ["#ifndef HELIX_SHA256_K_H", "#define HELIX_SHA256_K_H", "",
             "/* generated by tools/gen_vectors.py, fips 180-4:",
             " * iv = frac(sqrt(p))*2^32, k = frac(cbrt(p))*2^32, first",
             " * primes. do not edit. */", "", "#include <stdint.h>", "",
             "static const uint32_t SHA256_IV[8] = {",
             ", ".join("0x%08xu" % v for v in iv32), "};", "",
             "static const uint32_t SHA256_K[64] = {"]
    for i in range(0, 64, 4):
        lines.append("    " + ", ".join("0x%08xu" % v for v in k32[i:i + 4]) + ",")
    lines += ["};", "", "#endif", ""]
    emit("src/sha256_k.h", "\n".join(lines))
    lines = ["#ifndef HELIX_SHA512_K_H", "#define HELIX_SHA512_K_H", "",
             "/* generated by tools/gen_vectors.py, fips 180-4:",
             " * iv = frac(sqrt(p))*2^64, k = frac(cbrt(p))*2^64, first",
             " * primes. do not edit. */", "", "#include <stdint.h>", "",
             "static const uint64_t SHA512_IV[8] = {"]
    for i in range(0, 8, 2):
        lines.append("    " + ", ".join("0x%016xull" % v for v in iv64[i:i + 2]) + ",")
    lines += ["};", "", "static const uint64_t SHA512_K[80] = {"]
    for i in range(0, 80, 2):
        lines.append("    " + ", ".join("0x%016xull" % v for v in k64[i:i + 2]) + ",")
    lines += ["};", "", "#endif", ""]
    emit("src/sha512_k.h", "\n".join(lines))


def randbytes(rnd, n):
    return rnd.getrandbits(n * 8).to_bytes(n, "little") if n else b""


def sha_cases():
    rnd = random.Random(0x68656C6978)
    out = []
    for n in (0, 1, 55, 56, 63, 64, 65, 127, 128, 200):
        b = randbytes(rnd, n)
        out.append((n, b.hex(), hashlib.sha256(b).hexdigest(),
                    hashlib.sha512(b).hexdigest()))
    return out


def hmac_cases():
    out = [
        # rfc 4231 test case 1 and 2
        (bytes.fromhex("0b" * 20), b"Hi There"),
        (b"Jefe", b"what do ya want for nothing?"),
    ]
    rnd = random.Random(0x484D4143)
    for n in (1, 127, 128, 129):
        out.append((randbytes(rnd, n), randbytes(rnd, 37)))
    return [(k.hex(), m.hex(),
             hmac.new(k, m, hashlib.sha512).hexdigest())
            for k, m in out]


def pbkdf2_cases():
    cases = [
        (b"password", b"salt", 1, 64),
        (b"password", b"salt", 2, 64),
        (b"password", b"salt", 4096, 64),
        (b"passwordPASSWORDpASSWORd",
         b"saltSALTsaltSALTsaltSALTsaltSALTsalt", 4096, 100),
    ]
    rnd = random.Random(0x50424B32)
    salt = randbytes(rnd, 32)
    cases.append((b"helix-vector-password", salt, 600000, 64))
    return [(pw.hex(), s.hex(), it, dk,
             hashlib.pbkdf2_hmac("sha512", pw, s, it, dklen=dk).hex())
            for pw, s, it, dk in cases]


def bip39_cases():
    if os.path.exists(VECTORS_CACHE):
        v = json.load(open(VECTORS_CACHE))
    else:
        v = json.loads(urllib.request.urlopen(VECTORS_URL, timeout=30).read())
        open(VECTORS_CACHE, "w").write(json.dumps(v, indent=1))
    eng = v["english"]
    assert len(eng) == 24
    return [(e, m, s) for e, m, s, _ in eng]


def header(path, guard, body):
    emit(path, "\n".join([
        "#ifndef %s" % guard, "#define %s" % guard, "",
        "/* generated by tools/gen_vectors.py,",
        " * sources: python3 hashlib/hmac stdlib and the official",
        " * bip-0039 english vector set (passphrase TREZOR).",
        " * do not edit. */", "", body, "#endif", ""]))


RFC8439_PATH = "/tmp/rfc8439.txt"
RFC8439_URL = "https://www.rfc-editor.org/rfc/rfc8439.txt"


def rfc8439_text():
    import os
    if os.path.exists(RFC8439_PATH):
        return open(RFC8439_PATH).read()
    open(RFC8439_PATH, "w").write(
        urllib.request.urlopen(RFC8439_URL, timeout=30).read().decode())
    return open(RFC8439_PATH).read()


def rfc_section(t, start_marker, end_marker):
    i = t.find(start_marker, 9000)
    j = t.find(end_marker, i)
    assert i > 0 and j > i, (start_marker, i, j)
    return t[i:j]


def hexdump_bytes(seg):
    import re
    out = []
    for m in re.finditer(r"^\s*\d+\s+((?:[0-9a-f]{2} )+)", seg, re.M):
        out += [int(x, 16) for x in m.group(1).split()]
    return out


def colon_hex(seg, n):
    import re
    m = re.search(r"((?:[0-9a-f]{2}:){" + str(n - 1) + r"}[0-9a-f]{2})", seg)
    assert m, "colon hex not found"
    return [int(x, 16) for x in m.group(1).split(":")]


def word_rows(seg, count):
    import re
    rows = re.findall(r"^\s+([0-9a-f]{8}(?:\s+[0-9a-f]{8}){3})\s*$", seg, re.M)
    assert len(rows) >= count, (len(rows), count)
    words = []
    for r in rows[:count]:
        words += [int(w, 16) for w in r.split()]
    return words


def gen_rfc8439():
    t = rfc8439_text()
    hdr = ["#ifndef HELIX_RFC8439_VECTORS_INC",
           "#define HELIX_RFC8439_VECTORS_INC", "",
           "/* generated by tools/gen_vectors.py, extracted verbatim from",
           " * rfc 8439 sections 2.3.2, 2.4.2, 2.5.2, 2.6.2, 2.8.2.",
           " * do not edit. */", "",
           "#include <stdint.h>", ""]

    # 2.3.2 block function
    seg = rfc_section(t, "Test Vector for the ChaCha20 Block Function",
                      "2.4.  The ChaCha20 Encryption Algorithm")
    # the block function output is the state AFTER adding the
    # original: second matrix in the section (first is pre-add)
    out = word_rows(seg[seg.find("ChaCha state after 20 rounds"):], 8)
    out = out[16:32]
    assert len(out) == 16
    import struct
    out64 = struct.pack("<16I", *out).hex()
    hdr += ["/* 2.3.2 block function: key 00..1f, nonce 000000090000004a00000000,",
            " * counter 1 */",
            'static const unsigned char RFC_BLOCK_OUT[64] = {']
    hdr += ["    " + ", ".join("0x%02x" % b
                              for b in bytes.fromhex(out64)) + "};", ""]

    # 2.4.2 cipher
    seg = rfc_section(t, "Example and Test Vector for the ChaCha20 Cipher",
                      "2.5.  The Poly1305 Algorithm")
    pt = hexdump_bytes(seg[seg.find("Plaintext Sunscreen:"):
                           seg.find("Ciphertext Sunscreen:")])
    ct = hexdump_bytes(seg[seg.find("Ciphertext Sunscreen:"):])
    assert len(pt) == 114 and len(ct) == 114, (len(pt), len(ct))
    nonce = colon_hex(seg[seg.find("o  Nonce ="):
                          seg.find("Initial Counter")], 12)
    assert len(nonce) == 12

    def arr(name, data, comment):
        lines = [comment, "static const unsigned char %s[%d] = {" % (name, len(data))]
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
        return lines

    hdr += arr("RFC_CIPHER_PT", pt, "/* 2.4.2 cipher plaintext (114 bytes) */")
    hdr += arr("RFC_CIPHER_CT", ct, "/* 2.4.2 cipher ciphertext */")
    hdr += arr("RFC_CIPHER_NONCE", nonce, "/* 2.4.2 cipher nonce */")

    # 2.5.2 poly1305
    seg = rfc_section(t, "2.5.2.  Poly1305 Example and Test Vector",
                      "2.6.  Generating the Poly1305 Key")
    # the key material hex is line wrapped mid pair; join before parsing
    pk_seg = seg[seg.find("Key Material:"):]
    pk = colon_hex("".join(pk_seg[:260].split()), 32)
    tag = colon_hex("".join(seg[seg.find("Tag: a8"):].split()), 16)
    assert len(pk) == 32 and len(tag) == 16
    hdr += arr("RFC_POLY_KEY", pk, "/* 2.5.2 poly1305 key */")
    hdr += arr("RFC_POLY_TAG", tag,
               '/* 2.5.2 poly1305 tag over "Cryptographic Forum Research '
               'Group" */')

    # 2.6.2 poly keygen
    seg = rfc_section(t, "2.6.2.  Poly1305 Key Generation Test Vector",
                      "2.7.  A Pseudorandom Function")
    pgk = hexdump_bytes(seg[seg.find("Key:"):seg.find("Nonce:")])
    pgn = hexdump_bytes(seg[seg.find("Nonce:"):seg.find("The ChaCha state")])
    pkk = hexdump_bytes(seg[seg.find("Output bytes:"):])
    assert len(pgk) == 32 and len(pgn) == 12 and len(pkk) == 32, \
        (len(pgk), len(pgn), len(pkk))
    hdr += arr("RFC_POLYGEN_KEY", pgk, "/* 2.6.2 poly keygen key */")
    hdr += arr("RFC_POLYGEN_NONCE", pgn, "/* 2.6.2 poly keygen nonce */")
    hdr += arr("RFC_POLYGEN_OUT", pkk, "/* 2.6.2 poly keygen output */")

    # 2.8.2 aead
    seg = rfc_section(t, "Example and Test Vector for AEAD_CHACHA20_POLY1305",
                      "3.  Implementation Advice")
    apt = hexdump_bytes(seg[seg.find("Plaintext:"):seg.find("AAD:")])
    aad = hexdump_bytes(seg[seg.find("AAD:"):seg.find("Key:")])
    ak = hexdump_bytes(seg[seg.find("Key:"):seg.find("IV:")])
    aiv = hexdump_bytes(seg[seg.find("IV:"):seg.find("32-bit")])
    act = hexdump_bytes(seg[seg.find("Ciphertext:"):
                            seg.find("AEAD Construction for Poly1305:")])
    atag = colon_hex("".join(seg[seg.rfind("Tag:"):].split()), 16)
    assert len(apt) == 114 and len(aad) == 12 and len(ak) == 32, \
        (len(apt), len(aad), len(ak))
    assert len(aiv) == 8 and len(act) == 114 and len(atag) == 16, \
        (len(aiv), len(act), len(atag))
    hdr += arr("RFC_AEAD_KEY", ak, "/* 2.8.2 aead key */")
    hdr += arr("RFC_AEAD_AAD", aad, "/* 2.8.2 aead aad */")
    hdr += arr("RFC_AEAD_PT", apt, "/* 2.8.2 aead plaintext */")
    hdr += arr("RFC_AEAD_CT", act, "/* 2.8.2 aead ciphertext */")
    hdr += arr("RFC_AEAD_TAG", atag, "/* 2.8.2 aead tag */")
    hdr += ["/* aead nonce = 32-bit fixed-common part 07000000 (le) + IV */",
            "static const unsigned char RFC_AEAD_NONCE[12] = {",
            "    0x07, 0x00, 0x00, 0x00, " +
            ", ".join("0x%02x" % b for b in aiv),
            "};", "", "#endif", ""]
    emit("tests/rfc8439_vectors_inc.h", "\n".join(hdr))
    print("rfc8439 vectors extracted (block, cipher, poly, polygen, aead)")


def main():
    gen_wordlist()
    gen_sha_tables()
    gen_rfc8439()

    sc = "".join('    {%d, "%s",\n     "%s",\n     "%s"},\n'
                 % (n, ih, o256, o512) for n, ih, o256, o512 in sha_cases())
    header("tests/sha_vectors_inc.h", "HELIX_SHA_VECTORS_INC",
           "static const struct { int len; const char* input;"
           " const char* out256; const char* out512; } SHA_CASES[] = {\n"
           + sc + "};\n")

    hc = "".join('    {"%s",\n     "%s",\n     "%s"},\n' % (k, m, o)
                 for k, m, o in hmac_cases())
    header("tests/hmac_vectors_inc.h", "HELIX_HMAC_VECTORS_INC",
           "static const struct { const char* key; const char* msg;"
           " const char* out; } HMAC_CASES[] = {\n" + hc + "};\n")

    pc = "".join('    {"%s", "%s", %du, %d,\n     "%s"},\n'
                 % (p, s, it, dk, o) for p, s, it, dk, o in pbkdf2_cases())
    header("tests/pbkdf2_vectors_inc.h", "HELIX_PBKDF2_VECTORS_INC",
           "static const struct { const char* pass; const char* salt;"
           " unsigned iters; int dk_len; const char* out;"
           " } PBKDF2_CASES[] = {\n" + pc + "};\n")

    bc = "".join('    {"%s",\n     "%s",\n     "%s"},\n' % (e, m, s)
                 for e, m, s in bip39_cases())
    header("tests/bip39_vectors_inc.h", "HELIX_BIP39_VECTORS_INC",
           '#define BIP39_VECTOR_PASSPHRASE "TREZOR"\n'
           'static const struct { const char* entropy; const char* mnemonic;'
           ' const char* seed; } BIP39_CASES[] = {\n' + bc + "};\n")

    print("vectors: %d sha, %d hmac, %d pbkdf2, %d bip39"
          % (len(sha_cases()), len(hmac_cases()), len(pbkdf2_cases()),
             len(bip39_cases())))


main()
