/* vector tests: sha256, sha512, hmac-sha512, pbkdf2-hmac-sha512.
   expected values generated by tools/gen_vectors.py from python
   hashlib/hmac stdlib and rfc 4231. exit nonzero on any failure. */
#include <stdio.h>
#include <string.h>

#include "hex.h"
#include "sha256.h"
#include "sha512.h"
#include "hmac.h"
#include "pbkdf2.h"

#include "sha_vectors_inc.h"
#include "hmac_vectors_inc.h"
#include "pbkdf2_vectors_inc.h"

static int g_fail;
static int g_ok;

static void check(int ok, const char* what)
{
    if (ok) {
        g_ok++;
        return;
    }
    g_fail++;
    printf("FAIL: %s\n", what);
}

static void test_sha(void)
{
    size_t i;
    for (i = 0; i < sizeof SHA_CASES / sizeof SHA_CASES[0]; i++) {
        /* input arrives as hex text; decode it first */
        uint8_t buf[256];
        size_t n = 0;
        uint8_t out256[SHA256_DIGEST];
        uint8_t out512[SHA512_DIGEST];
        char got[2 * SHA512_DIGEST + 1];
        char what[64];
        if (hex_decode(SHA_CASES[i].input, buf, sizeof buf, &n) != 0 ||
            n != (size_t)SHA_CASES[i].len) {
            check(0, "sha vector decode");
            continue;
        }
        sha256(buf, n, out256);
        hex_encode(out256, SHA256_DIGEST, got);
        snprintf(what, sizeof what, "sha256 case %d", (int)i);
        check(strcmp(got, SHA_CASES[i].out256) == 0, what);
        sha512(buf, n, out512);
        hex_encode(out512, SHA512_DIGEST, got);
        snprintf(what, sizeof what, "sha512 case %d", (int)i);
        check(strcmp(got, SHA_CASES[i].out512) == 0, what);
    }
}

static void test_hmac(void)
{
    size_t i;
    for (i = 0; i < sizeof HMAC_CASES / sizeof HMAC_CASES[0]; i++) {
        uint8_t key[256];
        uint8_t msg[256];
        size_t klen = 0, mlen = 0;
        uint8_t out[SHA512_DIGEST];
        char got[2 * SHA512_DIGEST + 1];
        char what[64];
        hmac_sha512_ctx hc;
        if (hex_decode(HMAC_CASES[i].key, key, sizeof key, &klen) != 0 ||
            hex_decode(HMAC_CASES[i].msg, msg, sizeof msg, &mlen) != 0) {
            check(0, "hmac vector decode");
            continue;
        }
        hmac_sha512_init(&hc, key, klen);
        hmac_sha512_update(&hc, msg, mlen);
        hmac_sha512_final(&hc, out);
        hex_encode(out, SHA512_DIGEST, got);
        snprintf(what, sizeof what, "hmac case %d", (int)i);
        check(strcmp(got, HMAC_CASES[i].out) == 0, what);
        /* streaming split must agree with the single update path */
        if (mlen > 2) {
            hmac_sha512_init(&hc, key, klen);
            hmac_sha512_update(&hc, msg, 1);
            hmac_sha512_update(&hc, msg + 1, mlen - 2);
            hmac_sha512_update(&hc, msg + mlen - 1, 1);
            hmac_sha512_final(&hc, out);
            hex_encode(out, SHA512_DIGEST, got);
            snprintf(what, sizeof what, "hmac split case %d", (int)i);
            check(strcmp(got, HMAC_CASES[i].out) == 0, what);
        }
    }
}

static void test_pbkdf2(void)
{
    size_t i;
    for (i = 0; i < sizeof PBKDF2_CASES / sizeof PBKDF2_CASES[0]; i++) {
        uint8_t pass[64];
        uint8_t salt[64];
        size_t plen = 0, slen = 0;
        uint8_t dk[128];
        size_t dkl = (size_t)PBKDF2_CASES[i].dk_len;
        char got[2 * sizeof dk + 1];
        char what[64];
        if (hex_decode(PBKDF2_CASES[i].pass, pass, sizeof pass, &plen) != 0 ||
            hex_decode(PBKDF2_CASES[i].salt, salt, sizeof salt, &slen) != 0) {
            check(0, "pbkdf2 vector decode");
            continue;
        }
        pbkdf2_sha512(pass, plen, salt, slen, PBKDF2_CASES[i].iters,
                      dk, dkl);
        hex_encode(dk, dkl, got);
        snprintf(what, sizeof what, "pbkdf2 case %d (%u iters)",
                 (int)i, PBKDF2_CASES[i].iters);
        check(strcmp(got, PBKDF2_CASES[i].out) == 0, what);
    }
}

int main(void)
{
    test_sha();
    test_hmac();
    test_pbkdf2();
    printf("test_vectors: %d ok, %d failed\n", g_ok, g_fail);
    return g_fail != 0;
}
