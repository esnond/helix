/* bip39 vector tests: all 24 official english vectors (entropy to
   mnemonic, mnemonic to entropy, mnemonic to seed with passphrase
   TREZOR) plus rejection cases. vectors generated by
   tools/gen_vectors.py from the trezor/python-mnemonic set. */
#include <stdio.h>
#include <string.h>

#include "hex.h"
#include "bip39.h"

#include "bip39_vectors_inc.h"

static int g_fail;
static int g_ok;

static void check(int ok, const char* what)
{
    if (ok) {
        g_ok++;
        return;
    }
    g_fail++;
    printf("FAIL: %s\n", what);
}

static void test_vectors(void)
{
    size_t i;
    for (i = 0; i < sizeof BIP39_CASES / sizeof BIP39_CASES[0]; i++) {
        uint8_t entropy[32];
        uint8_t ref[32];
        uint8_t seed[BIP39_SEED_LEN];
        size_t elen = 0, rlen = 0;
        char mnemonic[BIP39_MNEMONIC_MAX];
        char got[2 * BIP39_SEED_LEN + 1];
        char what[64];
        snprintf(what, sizeof what, "bip39 entropy->mnemonic case %d", (int)i);
        if (hex_decode(BIP39_CASES[i].entropy, entropy, sizeof entropy,
                       &elen) != 0) {
            check(0, what);
            continue;
        }
        check(bip39_entropy_to_mnemonic(entropy, elen, mnemonic,
                                        sizeof mnemonic) == 0 &&
              strcmp(mnemonic, BIP39_CASES[i].mnemonic) == 0, what);

        snprintf(what, sizeof what, "bip39 mnemonic->entropy case %d", (int)i);
        check(bip39_mnemonic_to_entropy(BIP39_CASES[i].mnemonic, entropy,
                                        sizeof entropy, &elen) == 0, what);
        hex_decode(BIP39_CASES[i].entropy, ref, sizeof ref, &rlen);
        snprintf(what, sizeof what, "bip39 entropy bytes case %d", (int)i);
        check(elen == rlen && memcmp(entropy, ref, rlen) == 0, what);

        snprintf(what, sizeof what, "bip39 seed case %d", (int)i);
        check(bip39_seed(BIP39_CASES[i].mnemonic, BIP39_VECTOR_PASSPHRASE,
                         seed) == 0, what);
        hex_encode(seed, BIP39_SEED_LEN, got);
        snprintf(what, sizeof what, "bip39 seed value case %d", (int)i);
        check(strcmp(got, BIP39_CASES[i].seed) == 0, what);
    }
}

static void test_reject(void)
{
    char bad[BIP39_MNEMONIC_MAX];
    uint8_t entropy[32];
    size_t elen = 0;
    /* valid vector 0 mnemonic, last word swapped -> checksum breaks */
    snprintf(bad, sizeof bad, "%s", BIP39_CASES[0].mnemonic);
    check(bip39_mnemonic_to_entropy(bad, entropy, sizeof entropy,
                                    &elen) == 0, "reject: baseline valid");
    snprintf(bad, sizeof bad, "%s", BIP39_CASES[0].mnemonic);
    strcpy(strrchr(bad, ' ') + 1, "abandon");
    check(bip39_mnemonic_to_entropy(bad, entropy, sizeof entropy,
                                    &elen) != 0, "reject: bad checksum");
    snprintf(bad, sizeof bad, "%s", BIP39_CASES[0].mnemonic);
    strcpy(strrchr(bad, ' ') + 1, "notaword");
    check(bip39_mnemonic_to_entropy(bad, entropy, sizeof entropy,
                                    &elen) != 0, "reject: unknown word");
    snprintf(bad, sizeof bad, "%s ", BIP39_CASES[0].mnemonic);
    check(bip39_mnemonic_to_entropy(bad, entropy, sizeof entropy,
                                    &elen) != 0, "reject: trailing space");
    check(bip39_mnemonic_to_entropy("abandon  abandon", entropy,
                                    sizeof entropy, &elen) != 0,
          "reject: doubled space");
    check(bip39_mnemonic_to_entropy("abandon", entropy, sizeof entropy,
                                    &elen) != 0, "reject: one word");
    check(bip39_entropy_to_mnemonic(entropy, 15, bad, sizeof bad) != 0,
          "reject: entropy not multiple of 4");
    check(bip39_entropy_to_mnemonic(entropy, 8, bad, sizeof bad) != 0,
          "reject: entropy too small");
}

int main(void)
{
    test_vectors();
    test_reject();
    printf("test_bip39: %d ok, %d failed\n", g_ok, g_fail);
    return g_fail != 0;
}
